"""Durable signed manual approvals, executed by the existing scheduler/lease owner.

No browser thread, automatic grant, broker or second operation ledger. The exact
accepted review stays on its original receipt and is never regenerated by a worker.
"""
import json
from contextvars import ContextVar
from types import SimpleNamespace

from app import db, shopify_drafts as drafts
from app.models import CatalogueOperation, Product, ScheduledTask, ScheduledTaskRun, ShopifyProductIdentity
from app.shopify_capacity import BackgroundYield, background_work
from app.shopify_connection import ShopifyAdapter, ShopifyError
from app.utils.operation_control import OperationLease, acquire_catalogue_operation, finish_catalogue_operation

KEY = 'shopify_manual_review'
_lease = ContextVar('accepted_manual_operation', default=None)


def executing_lease():
    value = _lease.get()
    if value:
        from app.shopify_capacity import guard_owner
        guard_owner()
    return value


def require_no_prior_recovery(product_id, reviewed):
    # Only these explicit, signed correction modes have their own narrow guards.
    if reviewed.get('mode') in {'variable_resume', 'package_correction'}:
        return
    from app.models import ShopifyPublishJob
    job = db.session.get(ShopifyPublishJob, product_id)
    identities = ShopifyProductIdentity.query.filter_by(product_id=product_id).all()
    operations = [db.session.get(CatalogueOperation, row.operation_id) for row in identities if row.operation_id]
    if ((job and job.state == 'recovery_required') or any(
            op and op.recovery_state not in {None, 'none'} for op in operations)):
        raise ShopifyError('Existing Recovery Required blocks this new update; no new Shopify write was attempted. '
            'Inspect the original operation and unresolved package evidence before separately authorised recovery.')


def accept(product_id, token, acknowledged):
    from flask import g
    from flask_login import current_user
    from app.shopify_progress import review_data
    from app.automatic_publishing import local_revision, require_admin
    from app.utils.operation_control import release_local_operation
    from app import scheduled_tasks as tasks
    require_admin(current_user.id)
    if acknowledged is not True:
        raise ShopifyError('Explicit publishing acknowledgement is required; no work was accepted.')
    reviewed = review_data(product_id, token, max_age=900)
    if not {'product_id','digest','config_digest'}.issubset(reviewed):
        raise ShopifyError('Review approval is incomplete; generate a fresh signed Review & Sync.')
    if len(json.dumps(reviewed).encode()) > 16384:
        raise ShopifyError('Signed review is outside the bounded manual approval contract.')
    product = db.get_or_404(Product, product_id)
    require_no_prior_recovery(product.id, reviewed)
    revision = local_revision(product)
    g.shopify_review_ticket = drafts.digest(token)
    mode = reviewed.get('classification') or reviewed.get('mode') or 'create'
    lease = acquire_catalogue_operation('shopify_draft_publish', {'product_id':product.id,
        'sku':product.sku,'title':product.title,'mode':mode,'scope':reviewed.get('scope','full')})
    try:
        op = db.session.get(CatalogueOperation, lease.id)
        scope = json.loads(op.scope)
        scope['manual_review'] = {'version':1,'reviewed':reviewed,'proof':drafts.digest(reviewed),
            'actor_id':current_user.id,'source_revision':revision,'accepted_at':drafts.now().isoformat(),
            'state':'queued'}
        op.scope=json.dumps(scope);op.status='pending'
        from app.publishing_progress import update
        update(op,stage='operation_accepted',message='Signed approval durably accepted; the server worker continues without this browser.',status='queued')
        tasks.enqueue(KEY, manual=True)  # commits approval and task together
        return lease
    except Exception:
        db.session.rollback()
        finish_catalogue_operation(lease.id,status='failed',error='Manual task could not be queued; no Shopify write was attempted.',recovery_state='none')
        raise
    finally:
        release_local_operation(lease.id)


def resume(lease):
    """Take the normal global operation slot without inserting another receipt."""
    from app.utils import operation_control as control
    if not control._catalogue_lock.acquire(blocking=False):
        raise BackgroundYield('Another local catalogue operation owns the execution slot.')
    try:
        other = CatalogueOperation.query.filter(CatalogueOperation.id != lease.id,
            CatalogueOperation.operation_type.in_(control.ALLOWED_OPERATION_TYPES),
            CatalogueOperation.status.in_({'running','pending'})).first()
        if other: raise BackgroundYield('Another durable catalogue operation is active.')
        with control._state_lock:
            control._active_operation={'id':lease.id,'operation_type':'shopify_draft_publish','started_at':drafts.now().isoformat()}
    except Exception:
        control._catalogue_lock.release();raise


def run_slice(run_id, owner, *, adapter=None):
    from app import scheduled_tasks as tasks
    from app.automatic_publishing import local_revision, require_admin
    from app.publishing_progress import update
    from app.utils.operation_control import release_local_operation, sanitize_operation_error
    run=db.session.get(ScheduledTaskRun,run_id)
    data=json.loads(run.data_json)
    fence=lambda:tasks.fence(KEY,run_id,owner)
    def guard():
        # Some existing executors autoflush their durable pending receipt before
        # save(). Do not contend with that same SQLite writer via a second
        # connection; fence its owner in the existing commit transaction.
        if db.session.connection().connection.driver_connection.in_transaction:
            fence()
        else:tasks.renew(KEY,run_id,owner)
    lease=None;context_token=None
    try:
        guard()
        if not data.get('operation_id'):
            op=CatalogueOperation.query.filter_by(operation_type='shopify_draft_publish',status='pending').order_by(CatalogueOperation.started_at).first()
            if not op or 'manual_review' not in json.loads(op.scope):
                return tasks.save_progress(KEY,run_id,owner,data,terminal='completed')
            data['operation_id']=op.id
            # Durable correlation BEFORE the first remote call, including a
            # crash in the first batch rather than only between completed slices.
            run.data_json=tasks.encoded(data);fence();db.session.commit()
        op=db.session.get(CatalogueOperation,data['operation_id'])
        lease=OperationLease(op.id,'shopify_draft_publish')
        scope=json.loads(op.scope);approval=scope['manual_review'];reviewed=approval['reviewed']
        if approval.get('state') in {'completed','failed','recovery_required'}:
            return tasks.save_progress(KEY,run_id,owner,data,terminal='completed')
        if approval.get('proof') != drafts.digest(reviewed): raise ShopifyError('Retained approval integrity is invalid; fresh merchant review required.')
        product=db.session.get(Product,scope['product_id'])
        resume(lease)
        scope['manual_worker']={'task_key':KEY,'run_id':run_id,'owner':owner}
        scope['manual_review']['state']='running'
        op.scope=json.dumps(scope)
        identity=ShopifyProductIdentity.query.filter_by(operation_id=op.id).first()
        # Crash recovery is deliberately limited to an exact acknowledged
        # pre-create prefix or known processing/verified evidence. Never replay
        # an unknown binary upload, Create, update or other mutation.
        package_correction = reviewed.get('mode') == 'package_correction'
        if identity and not package_correction and identity.state not in {'uploading','processing','verified','scoped_verified'}:
            proof=drafts.evidence(identity)
            candidate=SimpleNamespace(state='uploading',shopify_product_id=identity.shopify_product_id,
                reviewed_digest=identity.reviewed_digest,media_evidence_json=identity.media_evidence_json)
            if identity.state=='pending' and drafts.upload_pending(candidate):
                drafts.save(identity,proof,'uploading')
            else: raise ShopifyError('Interrupted or uncertain publishing stage requires the existing read-only recovery workflow; no mutation replayed.')
        if identity and identity.state=='uploading' and not drafts.upload_pending(identity):
            raise ShopifyError('Upload acknowledgement is incomplete; recovery review is required, not another upload.')

        def authority():
            guard();require_admin(approval['actor_id'])
            if drafts.configuration().fingerprint()!=reviewed['config_digest'] or local_revision(product)!=approval['source_revision']:
                raise ShopifyError('Source revision or connection changed after signed approval; retained work needs fresh review.')

        from app.shopify_variable_readback import pending as verification_pending
        op.status='pending' if identity and (identity.state=='processing' or verification_pending(identity)) else 'running'
        op.finished_at=None;op.error=None;op.products_attempted=1
        update(op,stage='worker_running',message='Server worker owns this approved operation.',status='running')
        fence();db.session.commit()
        context_token=_lease.set(lease)
        with background_work(guard,fence=fence,requests=100,seconds=120,publisher_authority=authority):
            adapter=adapter or ShopifyAdapter()
            if package_correction:
                authority()
                identity=drafts.execute_reviewed(reviewed,adapter,expected_product_id=product.id)
            elif identity and (identity.state=='processing' or verification_pending(identity)):
                data['readback_polls']=data.get('readback_polls',0)+1
                # Read-only even though the original operation was approved.
                with background_work(guard,fence=fence,requests=80,seconds=90):
                    identity=drafts.finalize_processing(identity,adapter)
                if verification_pending(identity):
                    authority()
                    from app.shopify_variable_readback import complete as finish_readback
                    identity=finish_readback(identity,adapter,allow_writes=True)
                elif identity.state=='verified' and drafts.evidence(identity).get('kind')=='variable':
                    authority()
                    from app.shopify_variables import complete_deferred_availability
                    identity=complete_deferred_availability(identity,adapter)
                from app.shopify_notifications import complete
                if complete(identity,drafts.evidence(identity)) and db.session.get(CatalogueOperation,lease.id).status!='succeeded':
                    finish_catalogue_operation(lease.id,status='succeeded',recovery_state='none',products_attempted=1,products_succeeded=1,products_failed=0)
                if identity.state=='processing' and data['readback_polls']>=12:
                    raise ShopifyError('Shopify media remains processing after bounded polls; use read-only recovery, not another upload or Create.')
            elif not identity or drafts.upload_pending(identity):
                if not identity:
                    require_no_prior_recovery(product.id, reviewed)
                authority()
                identity=drafts.execute_reviewed(reviewed,adapter,expected_product_id=product.id)
        op=db.session.get(CatalogueOperation,lease.id)
        if package_correction and op.status in {'failed','partial'}:
            # A definite input rejection is not a transport-uncertain write.
            # The original package blocker remains in the queue/history either
            # way; do not let the generic publisher exception overwrite this
            # exact operation's retained acknowledgement/rejection outcome.
            proof=drafts.evidence(identity).get('package_assignments',{}).get(reviewed['package']['identity'],{})
            rejected=proof.get('state')=='rejected'
            scope=json.loads(op.scope);scope['manual_review']['state']='failed' if rejected else 'recovery_required'
            op.scope=json.dumps(scope)
            update(op,stage='package_assignment_rejected' if rejected else 'recovery_required',
                message=op.error or 'Inspect retained package evidence; no automatic replay.',status='failed' if rejected else 'recovery_required')
            fence();db.session.commit()
            return tasks.save_progress(KEY,run_id,owner,data,terminal='failed',error=op.error)
        if identity and (drafts.upload_pending(identity) or identity.state=='processing'):
            op.status='pending';op.finished_at=None
            scope=json.loads(op.scope);scope['manual_review']['state']='waiting';op.scope=json.dumps(scope)
            wait=drafts.evidence(identity).get('verification_wait') or {}
            update(op,stage='verification_pending' if wait else 'awaiting_shopify_processing' if identity.state=='processing' else 'waiting_for_next_batch',
                message=('Shopify writes acknowledged; awaiting complete readback without repeating mutations. '+str(wait.get('last_reason',''))) if wait else
                    'Durable progress retained; the next server slice continues independently of browser polling.',status='waiting')
            fence();db.session.commit()
            return tasks.save_progress(KEY,run_id,owner,data,pause=True,resume_seconds=15 if identity.state=='processing' else 1)
        if identity and op.status=='succeeded' and op.recovery_state in {None,'none'} and identity.state in {'verified','scoped_verified'}:
            scope=json.loads(op.scope);scope['manual_review']['state']='completed';op.scope=json.dumps(scope)
            update(op,stage='operation_completed',message='Reviewed work completed with its retained verification scope.',status='completed')
            fence();db.session.commit()
            return tasks.save_progress(KEY,run_id,owner,data,terminal='completed')
        raise ShopifyError(op.error or (drafts.evidence(identity).get('error') if identity else None) or 'Publishing was not completely verified. Inspect its receipt before any retry.')
    except BackgroundYield:
        db.session.rollback()
        if lease:
            op=db.session.get(CatalogueOperation,lease.id)
            if op.status in {'running','pending'}:
                scope=json.loads(op.scope);scope['manual_review']['state']='waiting';op.scope=json.dumps(scope)
                op.status='pending';op.finished_at=None;op.error=None
                update(op,stage='worker_deferred',message='Worker deferred before continuing; retained approval and receipts remain protected. No failed mutation is inferred.',status='waiting')
                fence();db.session.commit()
        return tasks.save_progress(KEY,run_id,owner,data,pause=True)
    except Exception as exc:
        db.session.rollback()
        if lease:
            op=db.session.get(CatalogueOperation,lease.id);scope=json.loads(op.scope)
            identity=ShopifyProductIdentity.query.filter_by(operation_id=op.id).first()
            uncertain=bool(identity and (drafts.evidence(identity).get('create_attempted') or
                drafts.evidence(identity).get('upload_attempt',{}).get('state')=='pending' or identity.state not in {'pending','uploading','failed_before_create'}))
            scope['manual_review']['state']='recovery_required' if uncertain else 'failed';op.scope=json.dumps(scope)
            update(op,stage='recovery_required' if uncertain else 'operation_failed',message=sanitize_operation_error(exc),status='recovery_required' if uncertain else 'failed')
            fence();db.session.commit()
            acknowledged=bool(identity and drafts.evidence(identity).get('verification_wait'))
            if acknowledged and uncertain and identity.state=='processing':
                retained=drafts.evidence(identity);retained['verification_wait']['state']='recovery_required'
                retained['error']=sanitize_operation_error(exc);identity.verification_state='unverified'
                drafts.save(identity,retained,'uncertain')
            finish_catalogue_operation(op.id,status='partial' if uncertain else 'failed',recovery_state='review_required' if uncertain else 'none',error=str(exc),products_attempted=1,products_failed=0 if acknowledged else 1)
        return tasks.save_progress(KEY,run_id,owner,data,terminal='failed',error=str(exc))
    finally:
        if context_token is not None:_lease.reset(context_token)
        if lease:release_local_operation(lease.id)
